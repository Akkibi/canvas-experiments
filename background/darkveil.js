const sigmoid = (x) => float(1).div(exp(x.negate()).add(1));

const matMul = (m, v) =>
  vec4(m[0], m[1], m[2], m[3]).mul(v.x)
    .add(vec4(m[4], m[5], m[6], m[7]).mul(v.y))
    .add(vec4(m[8], m[9], m[10], m[11]).mul(v.z))
    .add(vec4(m[12], m[13], m[14], m[15]).mul(v.w));

const cppn = (coord, in0, in1, in2) => {
  const buf = [];
  buf[6] = vec4(coord.x, coord.y, in0.add(0.3948333106474662), in1.add(0.36));
  buf[7] = vec4(in2.add(0.14), length(coord), 0, 0);
  for (const [target, terms, bias] of CPPN) {
    let sum = vec4(bias[0], bias[1], bias[2], bias[3]);
    for (const [input, m] of terms) sum = sum.add(matMul(m, buf[input]));
    buf[target] = sigmoid(sum).toVar();
  }
  return buf[0].xyz;
};

const hueShiftRGB = (col, deg) => {
  const yiq = vec3(0.299, 0.587, 0.114).mul(col.x).add(vec3(0.596, -0.274, -0.322).mul(col.y)).add(vec3(0.211, -0.523, 0.312).mul(col.z));
  const rad = radians(deg);
  const c = cos(rad);
  const s = sin(rad);
  const shifted = vec3(yiq.x, yiq.y.mul(c).sub(yiq.z.mul(s)), yiq.y.mul(s).add(yiq.z.mul(c)));
  const rgb = vec3(1, 1, 1).mul(shifted.x).add(vec3(0.956, -0.272, -1.106).mul(shifted.y)).add(vec3(0.621, -0.647, 1.703).mul(shifted.z));
  return clamp(rgb, 0, 1);
};

const rand = (c) => fract(sin(dot(c, vec2(12.9898, 78.233))).mul(43758.5453));

// Screen nodes rebuilt from the plane's own UVs, so the shader code stays unchanged.
const resolution = uniform(new Vector2(1024, 1024));
const screenSize = resolution;
const screenUV = vec2(uv().x, uv().y.oneMinus());
const screenCoordinate = screenUV.mul(resolution);

const createDarkVeilMaterial = () => {
  const u = {
    time: uniform(0),
    hueShift: uniform(0),
    noise: uniform(0),
    scan: uniform(0),
    scanFreq: uniform(0),
    warp: uniform(0),
    lightMode: uniform(0),
    blur: uniform(0),
    seed: uniform(0),
    tint: uniform(new Color("#3d8bff")),
    tintAmount: uniform(1),
  };

  const material = new MeshBasicNodeMaterial({ depthWrite: false });
  material.colorNode = Fn(() => {
    const st = screenUV.add(stochasticOffset(u.seed, u.blur.mul(0.01)));
    const fragCoord = vec2(screenCoordinate.x, screenSize.y.sub(screenCoordinate.y));
    const base = vec2(st.x, st.y.oneMinus()).mul(2).sub(1);
    const uv0 = vec2(base.x.mul(screenSize.x.div(screenSize.y)), base.y.negate());
    const t = u.time.mul(0.5);
    const uvw = uv0.add(vec2(sin(uv0.y.mul(6.283).add(t)), cos(uv0.x.mul(6.283).add(t))).mul(u.warp).mul(0.05));
    const cppnColor = cppn(uvw, sin(u.time.mul(0.3)).mul(0.1), sin(u.time.mul(0.69)).mul(0.1), sin(u.time.mul(0.44)).mul(0.1));

    const shifted = hueShiftRGB(cppnColor, u.hueShift);
    const scanline = sin(fragCoord.y.mul(u.scanFreq)).mul(0.5).add(0.5);
    const scanned = shifted.mul(float(1).sub(scanline.mul(scanline).mul(u.scan)));
    const result = clamp(scanned.add(rand(fragCoord.add(u.time)).sub(0.5).mul(u.noise)), 0, 1).toVar();

    const energy = max(result.r, max(result.g, result.b));
    const hue = result.div(max(energy, 0.001));
    const coverage = smoothstep(0.08, 0.82, energy);
    const ink = mix(hue.mul(0.32), hue.mul(0.78), smoothstep(0, 1, energy));
    const light = mix(vec3(1), ink, coverage.mul(0.82));
    const tinted = mix(result, u.tint.mul(energy), u.tintAmount);
    return vec4(mix(tinted, light, u.lightMode), 1);
  })();

  return { material, u };
};

export const createDarkVeil = (options = {}) => {
  const props = {
    hueShift: 0,
    noiseIntensity: 0,
    scanlineIntensity: 0,
    speed: 0.5,
    scanlineFrequency: 0,
    warpAmount: 0,
    lightMode: false,
    blur: 0,
    ...options,
  };
  const { material, u } = createDarkVeilMaterial();
  const mesh = new Mesh(new PlaneGeometry(2, 2), material);
  let last = performance.now();

  const update = () => {
    const now = performance.now();
    u.time.value += ((now - last) / 1000) * props.speed;
    last = now;
    u.hueShift.value = props.hueShift;
    u.noise.value = props.noiseIntensity;
    u.scan.value = props.scanlineIntensity;
    u.scanFreq.value = props.scanlineFrequency;
    u.warp.value = props.warpAmount;
    u.lightMode.value = props.lightMode ? 1 : 0;
    u.blur.value = props.blur;
    u.seed.value = (u.seed.value + 1) % 1024;
  };

  const setSize = (w, h) => resolution.value.set(w, h);

  return { mesh, update, setSize, props };
};
